import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { createServer } from 'node:http';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const root = process.cwd();
const output = path.resolve(process.argv[2] || path.join(root, 'artifacts', `annotation-smoke-${Date.now()}`));
await mkdir(output, { recursive: true });
const html = `<!doctype html><html lang="zh"><head><title>批注样本页</title><style>body{font:18px sans-serif;margin:60px}main{height:1500px}button{padding:16px 28px}p{width:500px}</style></head><body><main><h1>课程管理</h1><p>这里是当前页面的主要说明。</p><button id="action" onclick="window.businessClicks++">发布课程</button></main></body></html>`;
const server = createServer((_request, response) => { response.setHeader('Content-Type', 'text/html; charset=utf-8'); response.end(html); });
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const address = `http://127.0.0.1:${server.address().port}`;
const browser = await chromium.launch({ channel: 'chrome', headless: true });
try {
  const context = await browser.newContext({ viewport: { width: 1100, height: 820 }, permissions: ['clipboard-read', 'clipboard-write'] });
  const page = await context.newPage(); await page.goto(address);
  await page.evaluate(() => { window.businessClicks = 0; });
  await page.addScriptTag({ content: await readFile(path.join(root, 'desktop/presentation/annotation.js'), 'utf8') });
  const target = page.locator('#action'), rect = await target.boundingBox();
  const pending = page.evaluate(() => window.playbookAnnotations.start());
  await page.mouse.move(rect.x + rect.width / 2, rect.y + rect.height / 2);
  await page.screenshot({ path: path.join(output, '01-inspect.png') });
  await page.mouse.click(rect.x + rect.width / 2, rect.y + rect.height / 2);
  assert.equal(await page.evaluate(() => window.businessClicks), 0, 'element selection must not click the business button');
  assert.equal((await page.evaluate(() => window.playbookAnnotations.inspect())).formVisible, true);
  await page.keyboard.type('发布按钮缺少二次确认，建议显示课程名称。');
  await page.keyboard.press('Tab'); await page.keyboard.press('Tab'); await page.keyboard.press('Enter');
  const draft = await pending;
  assert.equal(draft.element.selector, '#action'); assert.equal(draft.page.title, '批注样本页');
  assert.match(draft.element.text, /发布课程/);
  const annotation = { id: 'sample-1', body: draft.body, element: draft.element };
  const prompt = `Playbook 批注 v1：${draft.body}`;
  await page.evaluate(value => window.playbookAnnotations.commit(value.annotation, value.prompt), { annotation, prompt });
  await page.waitForFunction(() => window.playbookAnnotations.inspect().pins[0]?.rect.x > 20);
  let state = await page.evaluate(() => window.playbookAnnotations.inspect());
  assert.equal(state.pinCount, 1); assert.equal(state.pins[0].visible, true);
  await page.screenshot({ path: path.join(output, '02-pin.png') });
  const pin = state.pins[0].rect;
  await page.mouse.click(pin.x + pin.width / 2, pin.y + pin.height / 2);
  state = await page.evaluate(() => window.playbookAnnotations.inspect());
  assert.equal(state.detailVisible, true);
  await page.screenshot({ path: path.join(output, '03-open.png') });
  await page.mouse.click(state.copyRect.x + state.copyRect.width / 2, state.copyRect.y + state.copyRect.height / 2);
  await page.waitForFunction(() => window.playbookAnnotations.inspect().copyStatus.includes('已复制'));
  assert.equal(await page.evaluate(() => navigator.clipboard.readText()), prompt);
  const second = page.evaluate(() => window.playbookAnnotations.start());
  await page.evaluate(() => window.playbookAnnotations.cancelPick());
  assert.equal(await second, null);
  await page.evaluate(() => document.querySelector('#action').remove());
  await page.waitForFunction(() => window.playbookAnnotations.inspect().pins[0].visible === false);
  await page.exposeFunction('__playbookDeleteAnnotation', async id => { assert.equal(id, annotation.id); throw new Error('删除写入失败'); });
  await page.evaluate(() => { document.querySelector('main').insertAdjacentHTML('beforeend', '<button id="action">发布课程</button>'); });
  await page.waitForFunction(() => window.playbookAnnotations.inspect().pins[0].visible);
  state = await page.evaluate(() => window.playbookAnnotations.inspect());
  await page.mouse.click(state.pins[0].rect.x + 15, state.pins[0].rect.y + 15);
  state = await page.evaluate(() => window.playbookAnnotations.inspect());
  await page.mouse.click(state.deleteRect.x + state.deleteRect.width / 2, state.deleteRect.y + state.deleteRect.height / 2);
  await page.waitForFunction(() => window.playbookAnnotations.inspect().copyStatus === '删除写入失败');
  assert.equal((await page.evaluate(() => window.playbookAnnotations.inspect())).pinCount, 1);
  await page.evaluate(id => window.playbookAnnotations.remove(id), annotation.id);
  state = await page.evaluate(() => window.playbookAnnotations.inspect());
  assert.equal(state.pinCount, 0); assert.equal(state.detailVisible, false);
  await page.evaluate(value => window.playbookAnnotations.commit(value.annotation, value.prompt), { annotation, prompt });
  assert.equal((await page.evaluate(() => window.playbookAnnotations.inspect())).pinCount, 0, 'late save acknowledgement cannot recreate a deleted pin');
  await page.evaluate(() => window.playbookAnnotations.dispose());
  assert.equal(await page.locator('#playbook-annotations').count(), 0);
  await writeFile(path.join(output, 'result.json'), JSON.stringify({ passed: true, draft, prompt, businessClicks: 0, screenshots: ['01-inspect.png', '02-pin.png', '03-open.png'] }, null, 2));
  console.log(JSON.stringify({ passed: true, output }));
} finally { await browser.close(); await new Promise(resolve => server.close(resolve)); }
