  presentation:{spotlightFeather:30,defaultHoldMs:1600,cursorMoveMs:750,openingMs:2400},
  narration:{enabled:true,voice:'Tingting',rate:200,opening:{text:'最后，为自己的智能体安装 Playbook Skill，创作、维护演示并复用 Playwright 测试。'}},
